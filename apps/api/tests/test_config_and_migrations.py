def test_production_refuses_a_stubbed_news_scorer() -> None:
    """The keyword stub is scaffolding; scoring customer-visible news with it
    would put a fake sentiment inside a real signal."""
    s = Settings(
        environment="production",
        jwt_secret="a-real-secret-from-the-platform-secret-store",
        auth_provider="clerk",
        database_url="postgresql+psycopg://u:p@ep-x.neon.tech/db",
        market_data_provider="auto",
        finnhub_api_key="a-real-key",
        llm_provider="fake",
    )
    with pytest.raises(RuntimeError, match="LLM_PROVIDER=fake"):
        s.assert_production_safe()


