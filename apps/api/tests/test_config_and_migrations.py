def test_cors_origins_parse_from_a_comma_list() -> None:
    s = Settings(cors_origins="http://a.test, https://b.test ,")
    assert s.cors_origin_list == ["http://a.test", "https://b.test"]


def test_migrations_match_the_models() -> None:
    """`alembic check` fails if a model changed without a migration. This is the
    same check CI runs, kept in the suite so it fails on a laptop first."""
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    cfg = Config(os.path.join(here, "alembic.ini"))
    cfg.set_main_option("script_location", os.path.join(here, "alembic"))
    cfg.set_main_option("sqlalchemy.url", os.environ["DATABASE_URL"])

    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"Models drifted from migrations. Generate a revision.\n{exc}")
