from __future__ import annotations

import os

import pytest

from app.core.config import Settings


def test_neon_style_url_is_pointed_at_psycopg3() -> None:
    s = Settings(database_url="postgres://u:p@host/db")
    assert s.database_url.startswith("postgresql+psycopg://")


def test_production_refuses_dev_defaults() -> None:
    """Better to fail at boot than to run production with a shared JWT secret."""
    s = Settings(
        environment="production",
        jwt_secret="dev-only-change-me-in-every-real-environment",
        auth_provider="local",
        database_url="postgresql+psycopg://u:p@localhost/db",
    )
    with pytest.raises(RuntimeError) as exc:
        s.assert_production_safe()
    message = str(exc.value)
    assert "JWT_SECRET" in message
    assert "AUTH_PROVIDER=local" in message
    assert "localhost" in message


